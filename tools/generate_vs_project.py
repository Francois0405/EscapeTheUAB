"""Regenerate visualstudio/EntornVGI.vcxproj from what CMake actually compiles.

CMake stays the primary build system. This script keeps the Visual Studio project in step
with it, so the source list is never maintained by hand. Libraries come from vcpkg.json
through the vcpkg MSBuild integration (manifest mode).

Usage, from the repository root, after `run-windows.cmd -NoRun`:
    python tools/generate_vs_project.py
    python tools/generate_vs_project.py --check    # fail if the project is out of date
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROJECT = ROOT / 'visualstudio' / 'EntornVGI.vcxproj'
FILTERS = ROOT / 'visualstudio' / 'EntornVGI.vcxproj.filters'


def cmake_sources(ninja: Path):
    """Source files of every game target (tests excluded), as paths used inside the project."""
    text = ninja.read_text(encoding='utf-8', errors='replace')
    sources = set()
    for target, source in re.findall(r'(?m)^build [^\n]*?: (?:CXX|C)_COMPILER__(\w+?)_(?:unscanned_)?Debug ([^\n|]+)', text):
        if 'Test' in target:
            continue
        path = source.strip().replace('$:', ':').replace('$ ', ' ').replace('\\', '/')
        vcpkg = re.search(r'/vcpkg_installed/[^/]+/include/(.+)$', path)
        if vcpkg:
            sources.add('$(VcpkgInstalledDir)$(VcpkgTriplet)\\include\\' + vcpkg.group(1).replace('/', '\\'))
            continue
        relative = Path(path).resolve().relative_to(ROOT)
        sources.add('..\\' + str(relative).replace('/', '\\'))
    if not sources:
        sys.exit(f'No sources found in {ninja}')
    return sorted(sources, key=str.lower)


def headers():
    found = []
    for folder in ('src',):
        found += ['..\\' + str(p.relative_to(ROOT)).replace('/', '\\') for p in (ROOT / folder).rglob('*.h')]
    return sorted(found, key=str.lower)


def object_names(sources):
    """Give sources that share a file name their own object file."""
    names = [s.rsplit('\\', 1)[-1].rsplit('.', 1)[0].lower() for s in sources]
    return {s: re.sub(r'[^A-Za-z0-9]+', '_', s.strip('.\\')) for s, n in zip(sources, names) if names.count(n) > 1}


def project(sources):
    unique = object_names(sources)
    compile_items = []
    for source in sources:
        if source in unique:
            compile_items.append(f'    <ClCompile Include="{source}">\n      <ObjectFileName>$(IntDir){unique[source]}.obj'
                                 f'</ObjectFileName>\n    </ClCompile>')
        else:
            compile_items.append(f'    <ClCompile Include="{source}" />')
    header_items = [f'    <ClInclude Include="{h}" />' for h in headers()]
    configurations = ''.join(f'''    <ProjectConfiguration Include="{c}|x64">
      <Configuration>{c}</Configuration>
      <Platform>x64</Platform>
    </ProjectConfiguration>
''' for c in ('Debug', 'Release'))
    includes = ';'.join([
        '$(VcpkgInstalledDir)$(VcpkgTriplet)\\include', '$(VcpkgInstalledDir)$(VcpkgTriplet)\\include\\bullet', '$(ProjectDir)..',
        '$(ProjectDir)..\\src', '$(ProjectDir)..\\src\\legacy_vgi', '$(ProjectDir)..\\src\\scene',
        '$(ProjectDir)..\\src\\platform', '$(ProjectDir)..\\third_party', '$(ProjectDir)..\\third_party\\imgui',
        '$(ProjectDir)..\\third_party\\imguizmo', '$(ProjectDir)..\\third_party\\SOIL2\\src',
        '$(ProjectDir)..\\third_party\\cgltf', '$(ProjectDir)..\\third_party\\miniaudio',
        '$(ProjectDir)..\\third_party\\stb_compat', '%(AdditionalIncludeDirectories)'])
    defines = ';'.join([
        'ENTORNVGI_HAS_ENET=1', 'ENTORNVGI_HAS_MESHOPTIMIZER=1', 'ENTORNVGI_HAS_OPENXR=1', 'ENTORNVGI_USE_NFD_EXTENDED',
        'GLFW_DLL', 'GLM_ENABLE_EXPERIMENTAL', 'MESHOPTIMIZER_API=__declspec(dllimport)', 'NFD_SHARED', 'NOMINMAX',
        '_CRT_SECURE_NO_WARNINGS', 'ENTORNVGI_SOURCE_ASSETS_DIR="$(RepositoryRootSlash)/assets"',
        'ENTORNVGI_RUNTIME_ASSETS_DIR="$(RepositoryRootSlash)/build/msbuild/assets"', 'WIN32', '_WINDOWS',
        '%(PreprocessorDefinitions)'])
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_vs_project.py. Do not edit the file list by hand. -->
<Project DefaultTargets="Build" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">
  <ItemGroup Label="ProjectConfigurations">
{configurations}  </ItemGroup>
  <PropertyGroup Label="Globals">
    <VCProjectVersion>18.0</VCProjectVersion>
    <ProjectGuid>{{f9482bd2-37e3-4568-abed-a98fbf131bc2}}</ProjectGuid>
    <RootNamespace>EntornVGI</RootNamespace>
    <WindowsTargetPlatformVersion>10.0</WindowsTargetPlatformVersion>
    <VcpkgEnabled>true</VcpkgEnabled>
    <VcpkgEnableManifest>true</VcpkgEnableManifest>
    <VcpkgManifestRoot>$(MSBuildThisFileDirectory)..\\</VcpkgManifestRoot>
    <VcpkgTriplet>x64-windows</VcpkgTriplet>
    <VcpkgInstalledDir>$(MSBuildThisFileDirectory)..\\build\\msbuild\\vcpkg_installed\\</VcpkgInstalledDir>
    <VcpkgDirectory>$(VCPKG_ROOT)</VcpkgDirectory>
  </PropertyGroup>
  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.Default.props" />
  <PropertyGroup Label="Configuration">
    <ConfigurationType>Application</ConfigurationType>
    <PlatformToolset>v145</PlatformToolset>
    <CharacterSet>MultiByte</CharacterSet>
    <UseDebugLibraries Condition="'$(Configuration)'=='Debug'">true</UseDebugLibraries>
    <UseDebugLibraries Condition="'$(Configuration)'=='Release'">false</UseDebugLibraries>
  </PropertyGroup>
  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.props" />
  <PropertyGroup>
    <VcpkgDirectory Condition="'$(VcpkgDirectory)'==''">$(VCInstallDir)vcpkg</VcpkgDirectory>
    <OutDir>$(MSBuildThisFileDirectory)..\\build\\msbuild\\$(Configuration)\\</OutDir>
    <IntDir>$(MSBuildThisFileDirectory)..\\build\\msbuild\\obj\\$(Configuration)\\</IntDir>
    <RepositoryRootSlash>$([System.IO.Path]::GetFullPath('$(MSBuildThisFileDirectory)..').Replace('\\', '/'))</RepositoryRootSlash>
    <LocalDebuggerWorkingDirectory>$(MSBuildThisFileDirectory)..</LocalDebuggerWorkingDirectory>
  </PropertyGroup>
  <Import Project="$(VcpkgDirectory)\\scripts\\buildsystems\\msbuild\\vcpkg.props" Condition="Exists('$(VcpkgDirectory)\\scripts\\buildsystems\\msbuild\\vcpkg.props')" />
  <ItemDefinitionGroup>
    <ClCompile>
      <WarningLevel>Level3</WarningLevel>
      <LanguageStandard>stdcpp20</LanguageStandard>
      <LanguageStandard_C>stdc11</LanguageStandard_C>
      <ExceptionHandling>Sync</ExceptionHandling>
      <MultiProcessorCompilation>true</MultiProcessorCompilation>
      <AdditionalIncludeDirectories>{includes}</AdditionalIncludeDirectories>
      <PreprocessorDefinitions>{defines}</PreprocessorDefinitions>
    </ClCompile>
    <Link>
      <SubSystem>Console</SubSystem>
      <GenerateDebugInformation>true</GenerateDebugInformation>
      <AdditionalDependencies>opengl32.lib;ws2_32.lib;winmm.lib;%(AdditionalDependencies)</AdditionalDependencies>
    </Link>
  </ItemDefinitionGroup>
  <ItemDefinitionGroup Condition="'$(Configuration)'=='Debug'">
    <ClCompile>
      <Optimization>Disabled</Optimization>
      <RuntimeLibrary>MultiThreadedDebugDLL</RuntimeLibrary>
    </ClCompile>
  </ItemDefinitionGroup>
  <ItemDefinitionGroup Condition="'$(Configuration)'=='Release'">
    <ClCompile>
      <Optimization>MaxSpeed</Optimization>
      <RuntimeLibrary>MultiThreadedDLL</RuntimeLibrary>
      <PreprocessorDefinitions>NDEBUG;%(PreprocessorDefinitions)</PreprocessorDefinitions>
    </ClCompile>
  </ItemDefinitionGroup>
  <ItemGroup>
{chr(10).join(compile_items)}
  </ItemGroup>
  <ItemGroup>
{chr(10).join(header_items)}
  </ItemGroup>
  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.targets" />
  <Import Project="$(VcpkgDirectory)\\scripts\\buildsystems\\msbuild\\vcpkg.targets" Condition="Exists('$(VcpkgDirectory)\\scripts\\buildsystems\\msbuild\\vcpkg.targets')" />
</Project>
'''


def filters(sources):
    def folder(path):
        if path.startswith('$('):
            return 'vcpkg'
        return path[3:].rsplit('\\', 1)[0]

    items = [('ClCompile', s) for s in sources] + [('ClInclude', h) for h in headers()]
    names = set()
    for _, path in items:
        parts = folder(path).split('\\')
        names.update('\\'.join(parts[:i]) for i in range(1, len(parts) + 1))
    body = ''.join(f'    <Filter Include="{n}" />\n' for n in sorted(names))
    entries = ''.join(f'    <{tag} Include="{path}">\n      <Filter>{folder(path)}</Filter>\n    </{tag}>\n'
                      for tag, path in items)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<Project ToolsVersion="4.0" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">\n'
            f'  <ItemGroup>\n{body}  </ItemGroup>\n  <ItemGroup>\n{entries}  </ItemGroup>\n</Project>\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--build-dir', default='build/windows-debug')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    ninja = ROOT / args.build_dir / 'build.ninja'
    if not ninja.exists():
        sys.exit(f'{ninja} does not exist. Run run-windows.cmd -NoRun first.')
    sources = cmake_sources(ninja)
    stale = []
    for path, text in ((PROJECT, project(sources)), (FILTERS, filters(sources))):
        data = text.replace('\n', '\r\n').encode('utf-8')
        if args.check:
            if not path.exists() or path.read_bytes().replace(b'\r\n', b'\n') != data.replace(b'\r\n', b'\n'):
                stale.append(path.name)
        else:
            path.write_bytes(data)
    if stale:
        sys.exit('Out of date, run tools/generate_vs_project.py: ' + ', '.join(stale))
    print(f'{len(sources)} sources')


if __name__ == '__main__':
    main()
